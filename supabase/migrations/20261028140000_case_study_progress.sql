-- Progreso de cada persona en los casos de estudio.
--
-- Una fila por (persona, caso) con el estado, la autoevaluacion, las notas y las
-- visitas, mas un historial de solo lectura que llenan la base y no la app.
-- Todo es privado: cada cuenta ve y escribe solo lo suyo, sea cual sea su rol.

-- ============================================================
-- Enums
-- ============================================================

-- Sin fila (o con status null) el caso esta "sin empezar".
--   pendiente    la persona lo guardo para hacerlo
--   en-progreso  lo esta resolviendo
--   completado   lo resolvio
--   revisado     lo volvio a repasar despues de completarlo
create type public.case_progress_status as enum (
    'pendiente', 'en-progreso', 'completado', 'revisado'
);

create type public.case_activity_kind as enum ('visita', 'estado', 'autoevaluacion');

-- ============================================================
-- Progreso
-- ============================================================

create table public.case_study_progress (
    profile_id        uuid not null references public.profiles (id) on delete cascade,
    case_study_id     bigint not null references public."CaseStudies" (id) on delete cascade,
    status            public.case_progress_status,
    self_rating       smallint check (self_rating between 1 and 5),
    notes             text check (char_length(notes) <= 5000),
    view_count        int not null default 0,
    first_viewed_at   timestamptz,
    last_viewed_at    timestamptz,
    status_changed_at timestamptz,
    completed_at      timestamptz,
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now(),
    primary key (profile_id, case_study_id)
);

comment on table public.case_study_progress is
    'Progreso privado de cada cuenta en cada caso de estudio.';

create index case_study_progress_case_idx on public.case_study_progress (case_study_id);

-- Las fechas del estado las pone la base: lo que mande el cliente en esas
-- columnas se ignora.
create function public.case_study_progress_stamp()
returns trigger
language plpgsql
as $$
begin
    new.updated_at := now();

    if tg_op = 'INSERT' then
        new.status_changed_at := case when new.status is null then null else now() end;
        new.completed_at := case when new.status = 'completado' then now() end;
    elsif new.status is distinct from old.status then
        new.status_changed_at := case when new.status is null then null else now() end;
        -- Se guarda la primera vez que lo completo: volver a "en progreso" o
        -- marcarlo "revisado" no borra cuando lo resolvio.
        new.completed_at := case
            when new.status = 'completado' and old.completed_at is null then now()
            else old.completed_at
        end;
    else
        new.status_changed_at := old.status_changed_at;
        new.completed_at := old.completed_at;
    end if;

    return new;
end;
$$;

create trigger case_study_progress_stamp
    before insert or update on public.case_study_progress
    for each row execute function public.case_study_progress_stamp();

-- ============================================================
-- Historial
-- ============================================================

create table public.case_study_activity (
    id            bigint generated by default as identity primary key,
    profile_id    uuid not null references public.profiles (id) on delete cascade,
    case_study_id bigint not null references public."CaseStudies" (id) on delete cascade,
    kind          public.case_activity_kind not null,
    status        public.case_progress_status,
    self_rating   smallint,
    created_at    timestamptz not null default now()
);

comment on table public.case_study_activity is
    'Historial del progreso en casos. Lo escriben triggers y record_case_view, nunca la app.';

create index case_study_activity_profile_idx on public.case_study_activity (profile_id, created_at desc);
create index case_study_activity_case_idx on public.case_study_activity (case_study_id);

-- SECURITY DEFINER porque nadie tiene policy de insert sobre el historial: asi
-- nadie puede escribirse entradas a mano, ni siquiera las propias.
create function public.case_study_progress_log()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    previous_status public.case_progress_status;
    previous_rating smallint;
begin
    if tg_op = 'UPDATE' then
        previous_status := old.status;
        previous_rating := old.self_rating;
    end if;

    if new.status is distinct from previous_status then
        insert into public.case_study_activity (profile_id, case_study_id, kind, status)
        values (new.profile_id, new.case_study_id, 'estado', new.status);
    end if;

    if new.self_rating is distinct from previous_rating then
        insert into public.case_study_activity (profile_id, case_study_id, kind, self_rating)
        values (new.profile_id, new.case_study_id, 'autoevaluacion', new.self_rating);
    end if;

    return null;
end;
$$;

create trigger case_study_progress_log
    after insert or update on public.case_study_progress
    for each row execute function public.case_study_progress_log();

-- ============================================================
-- Visitas
-- ============================================================

-- Registra que la persona abrio el caso. Recargar la pagina no cuenta como otra
-- visita: hace falta que pasen 30 minutos desde la anterior.
--
-- SECURITY DEFINER para escribir el historial; por eso comprueba la cuenta a
-- mano, igual que hace RLS con las escrituras directas.
create function public.record_case_view(p_case_study_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    me       uuid := auth.uid();
    previous timestamptz;
    counts   boolean;
begin
    if me is null or public.auth_role() is null then
        raise exception 'Necesitas una cuenta activa para guardar tu progreso'
            using errcode = '42501';
    end if;

    if not exists (select 1 from public."CaseStudies" where id = p_case_study_id) then
        raise exception 'Ese caso de estudio no existe' using errcode = 'P0002';
    end if;

    select last_viewed_at into previous
      from public.case_study_progress
     where profile_id = me and case_study_id = p_case_study_id;

    counts := previous is null or previous < now() - interval '30 minutes';

    insert into public.case_study_progress as p
        (profile_id, case_study_id, view_count, first_viewed_at, last_viewed_at)
    values (me, p_case_study_id, 1, now(), now())
    on conflict (profile_id, case_study_id) do update
        set view_count      = p.view_count + case when counts then 1 else 0 end,
            first_viewed_at = coalesce(p.first_viewed_at, now()),
            last_viewed_at  = now();

    if counts then
        insert into public.case_study_activity (profile_id, case_study_id, kind)
        values (me, p_case_study_id, 'visita');
    end if;
end;
$$;

-- ============================================================
-- RLS
-- ============================================================

alter table public.case_study_progress enable row level security;
alter table public.case_study_activity enable row level security;

-- Leer y borrar lo propio siempre se puede; escribir exige la cuenta activa,
-- igual que el resto de las capacidades (auth_role() es null si no lo esta).
create policy "case_progress_select_own" on public.case_study_progress
    for select to authenticated
    using (profile_id = auth.uid());

create policy "case_progress_insert_own" on public.case_study_progress
    for insert to authenticated
    with check (profile_id = auth.uid() and public.auth_role() is not null);

create policy "case_progress_update_own" on public.case_study_progress
    for update to authenticated
    using (profile_id = auth.uid())
    with check (profile_id = auth.uid() and public.auth_role() is not null);

create policy "case_progress_delete_own" on public.case_study_progress
    for delete to authenticated
    using (profile_id = auth.uid());

create policy "case_activity_select_own" on public.case_study_activity
    for select to authenticated
    using (profile_id = auth.uid());

-- ============================================================
-- Grants
-- ============================================================

-- Supabase da todo a anon y authenticated por defecto en tablas nuevas. Aqui se
-- deja solo lo que corresponde: el anonimo no tiene progreso, y el historial es
-- de solo lectura.
revoke all on public.case_study_progress from anon, authenticated;
revoke all on public.case_study_activity from anon, authenticated;

grant select, insert, update, delete on public.case_study_progress to authenticated;
grant select on public.case_study_activity to authenticated;
grant all on public.case_study_progress to service_role;
grant all on public.case_study_activity to service_role;

revoke execute on function public.record_case_view(bigint) from public, anon;
grant execute on function public.record_case_view(bigint) to authenticated, service_role;
